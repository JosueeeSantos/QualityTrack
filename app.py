
from flask import Flask, render_template, request, redirect
import psycopg
import os

app = Flask(__name__)

# CONEXÃO COM O BANCO DE DADOS NEON
DATABASE_URL = os.environ.get('DATABASE_URL')


def conectar_banco():
    if not DATABASE_URL:
        raise RuntimeError(
            'A variável de ambiente DATABASE_URL não foi configurada.'
        )

    return psycopg.connect(DATABASE_URL)


# CRIANDO A TABELA
def inicializar_banco():
    with conectar_banco() as conexao:
        with conexao.cursor() as cursor:
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS ocorrencias (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    produto TEXT NOT NULL,
                    defeito TEXT NOT NULL,
                    quantidade INTEGER NOT NULL
                )
            """)


inicializar_banco()


# PÁGINA PRINCIPAL E CADASTRO
@app.route('/', methods=['GET', 'POST'])
def inicio():

    mensagem = ''

    if request.method == 'POST':

        produto = request.form.get('produto', '').strip()
        defeito = request.form.get('defeito', '').strip()
        quantidade = request.form.get('quantidade', '')

        if not produto or not defeito:
            mensagem = 'Preencha todos os campos!'

        else:
            try:
                quantidade = int(quantidade)

                if quantidade <= 0:
                    mensagem = 'A quantidade deve ser maior que zero!'

                else:
                    with conectar_banco() as conexao:
                        with conexao.cursor() as cursor:
                            cursor.execute("""
                                INSERT INTO ocorrencias
                                (produto, defeito, quantidade)
                                VALUES (%s, %s, %s)
                            """, (produto, defeito, quantidade))

                    mensagem = 'Ocorrência cadastrada com sucesso!'

            except ValueError:
                mensagem = 'Digite uma quantidade válida!'

    return render_template('index.html', mensagem=mensagem)


# LISTAGEM DE OCORRÊNCIAS
@app.route('/ocorrencias')
def listar_ocorrencias():

    with conectar_banco() as conexao:
        with conexao.cursor() as cursor:
            cursor.execute("""
                SELECT * FROM ocorrencias
                ORDER BY id DESC
            """)

            registros = cursor.fetchall()

    return render_template(
        'ocorrencias.html',
        registros=registros
    )


# EDITAR OCORRÊNCIA
@app.route('/editar/<int:id>', methods=['GET', 'POST'])
def editar_ocorrencia(id):

    with conectar_banco() as conexao:
        with conexao.cursor() as cursor:

            cursor.execute(
                'SELECT * FROM ocorrencias WHERE id = %s',
                (id,)
            )

            registro = cursor.fetchone()

            if registro is None:
                return 'Ocorrência não encontrada.', 404

            if request.method == 'POST':

                produto = request.form.get('produto', '').strip()
                defeito = request.form.get('defeito', '').strip()
                quantidade_texto = request.form.get('quantidade', '')

                try:
                    quantidade = int(quantidade_texto)

                    if not produto or not defeito or quantidade <= 0:
                        raise ValueError

                    cursor.execute("""
                        UPDATE ocorrencias
                        SET produto = %s, defeito = %s, quantidade = %s
                        WHERE id = %s
                    """, (produto, defeito, quantidade, id))

                    return redirect('/ocorrencias')

                except ValueError:

                    mensagem = 'Preencha os campos corretamente!'

                    registro = (
                        registro[0],
                        produto,
                        defeito,
                        quantidade_texto
                    )

                    return render_template(
                        'editar.html',
                        registro=registro,
                        mensagem=mensagem
                    )

    return render_template(
        'editar.html',
        registro=registro
    )


# EXCLUIR OCORRÊNCIA
@app.route('/excluir/<int:id>', methods=['POST'])
def excluir_ocorrencia(id):

    with conectar_banco() as conexao:
        with conexao.cursor() as cursor:
            cursor.execute("""
                DELETE FROM ocorrencias
                WHERE id = %s
            """, (id,))

    return redirect('/ocorrencias')


# DASHBOARD DE INDICADORES
@app.route('/dashboard')
def dashboard():

    with conectar_banco() as conexao:
        with conexao.cursor() as cursor:

            # TOTAL DE OCORRÊNCIAS
            cursor.execute("""
                SELECT COUNT(*) FROM ocorrencias
            """)

            total_ocorrencias = cursor.fetchone()[0]

            # TOTAL DE PEÇAS AFETADAS
            cursor.execute("""
                SELECT SUM(quantidade) FROM ocorrencias
            """)

            total_pecas = cursor.fetchone()[0] or 0

            # TIPOS DIFERENTES DE DEFEITOS
            cursor.execute("""
                SELECT COUNT(DISTINCT defeito)
                FROM ocorrencias
            """)

            total_tipos = cursor.fetchone()[0]

            # REGISTROS AGRUPADOS POR DEFEITO
            cursor.execute("""
                SELECT defeito, COUNT(*), SUM(quantidade)
                FROM ocorrencias
                GROUP BY defeito
                ORDER BY COUNT(*) DESC
            """)

            defeitos = cursor.fetchall()

    defeito_mais_frequente = (
        defeitos[0][0] if defeitos else 'Nenhum'
    )

    return render_template(
        'dashboard.html',
        total_ocorrencias=total_ocorrencias,
        total_pecas=total_pecas,
        total_tipos=total_tipos,
        defeito_mais_frequente=defeito_mais_frequente,
        defeitos=defeitos
    )


if __name__ == '__main__':
    app.run(debug=False)
